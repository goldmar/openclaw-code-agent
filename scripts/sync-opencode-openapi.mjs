#!/usr/bin/env node
// Vendors the OpenCode server's OpenAPI document into
// tests/protocol/opencode-openapi.json from the locally installed `opencode`.
//
// Usage: node scripts/sync-opencode-openapi.mjs [--opencode <bin>] [--check]
//
// Starts `opencode serve --hostname 127.0.0.1 --port 0` under a throwaway
// HOME/XDG profile (no user state is read or written), reads the bound URL from
// its `opencode server listening on <url>` line, fetches `/doc`, and keeps only
// the operations in OPERATIONS plus the closure of the component schemas they
// reference. Tests validate the fake OpenCode server's HTTP and SSE shapes
// against it (tests/protocol-schema.ts). The document records the OpenCode
// version it came from (`x-oca-source-version`). Never edit it by hand.
// `--check` fails when the vendored document differs from a fresh generation.

import { spawn, execFileSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";

// [path, method] pairs the harness calls, plus the SSE stream.
const OPERATIONS = [
  ["/global/event", "get"],
  ["/session", "post"],
  ["/session/status", "get"],
  ["/session/{sessionID}", "get"],
  ["/session/{sessionID}", "patch"],
  ["/session/{sessionID}/message", "get"],
  ["/session/{sessionID}/prompt_async", "post"],
  ["/session/{sessionID}/abort", "post"],
  ["/session/{sessionID}/fork", "post"],
  ["/permission/{requestID}/reply", "post"],
  ["/question/{requestID}/reply", "post"],
];

const LISTENING_LINE = /opencode server listening on (https?:\/\/\S+)/;
const STARTUP_TIMEOUT_MS = 60_000;

const repoRoot = resolve(dirname(new URL(import.meta.url).pathname), "..");
const target = join(repoRoot, "tests", "protocol", "opencode-openapi.json");

function parseArgs(argv) {
  const args = { opencode: "opencode", check: false };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--opencode") args.opencode = argv[++i];
    else if (argv[i] === "--check") args.check = true;
    else throw new Error(`Unknown argument: ${argv[i]}`);
  }
  return args;
}

async function fetchDocument(bin, profileDir) {
  const env = {
    ...process.env,
    HOME: profileDir,
    XDG_CONFIG_HOME: join(profileDir, "config"),
    XDG_DATA_HOME: join(profileDir, "data"),
    XDG_STATE_HOME: join(profileDir, "state"),
    XDG_CACHE_HOME: join(profileDir, "cache"),
  };
  const child = spawn(bin, ["serve", "--hostname", "127.0.0.1", "--port", "0"], {
    cwd: profileDir,
    env,
    stdio: ["ignore", "pipe", "pipe"],
  });
  try {
    const baseUrl = await new Promise((resolveUrl, reject) => {
      let output = "";
      const timer = setTimeout(() => reject(new Error(`opencode serve did not report its URL within ${STARTUP_TIMEOUT_MS} ms:\n${output}`)), STARTUP_TIMEOUT_MS);
      const onData = (chunk) => {
        output += chunk.toString();
        const match = LISTENING_LINE.exec(output);
        if (match) {
          clearTimeout(timer);
          resolveUrl(match[1].replace(/\/$/, ""));
        }
      };
      child.stdout.on("data", onData);
      child.stderr.on("data", onData);
      child.once("exit", (code, signal) => {
        clearTimeout(timer);
        reject(new Error(`opencode serve exited early (${signal ?? `code ${code}`}):\n${output}`));
      });
    });
    const response = await fetch(`${baseUrl}/doc`);
    if (!response.ok) throw new Error(`GET /doc failed with ${response.status}`);
    return await response.json();
  } finally {
    child.kill("SIGTERM");
  }
}

function prune(doc, version) {
  const paths = {};
  for (const [path, method] of OPERATIONS) {
    const operation = doc.paths?.[path]?.[method];
    if (!operation) throw new Error(`OpenCode OpenAPI has no ${method.toUpperCase()} ${path}`);
    paths[path] = { ...(paths[path] ?? {}), [method]: operation };
  }
  const schemas = doc.components?.schemas ?? {};
  const kept = new Set();
  const queue = [paths];
  while (queue.length > 0) {
    const node = queue.pop();
    if (!node || typeof node !== "object") continue;
    if (Array.isArray(node)) { queue.push(...node); continue; }
    if (typeof node.$ref === "string") {
      const match = /^#\/components\/schemas\/(.+)$/.exec(node.$ref);
      if (!match) throw new Error(`Unsupported $ref in OpenCode OpenAPI: ${node.$ref}`);
      if (!kept.has(match[1])) {
        if (!schemas[match[1]]) throw new Error(`OpenCode OpenAPI is missing ${node.$ref}`);
        kept.add(match[1]);
        queue.push(schemas[match[1]]);
      }
    }
    for (const value of Object.values(node)) if (value && typeof value === "object") queue.push(value);
  }
  return {
    "x-oca-comment": "GENERATED CODE! DO NOT MODIFY BY HAND! Generated by scripts/sync-opencode-openapi.mjs from `opencode serve` GET /doc, pruned to the operations the harness uses.",
    "x-oca-source-version": version,
    openapi: doc.openapi,
    info: doc.info,
    paths,
    components: { schemas: Object.fromEntries([...kept].sort().map((name) => [name, schemas[name]])) },
  };
}

const args = parseArgs(process.argv.slice(2));
const version = `opencode ${execFileSync(args.opencode, ["--version"], { encoding: "utf8" }).trim()}`;
const profileDir = mkdtempSync(join(tmpdir(), "oca-opencode-openapi-"));
let content;
try {
  content = `${JSON.stringify(prune(await fetchDocument(args.opencode, profileDir), version), null, 2)}\n`;
} finally {
  rmSync(profileDir, { recursive: true, force: true });
}

if (args.check) {
  const existing = existsSync(target) ? readFileSync(target, "utf8") : undefined;
  if (existing !== content) {
    const vendored = existing ? JSON.parse(existing)["x-oca-source-version"] : "nothing";
    console.error(`Vendored OpenCode OpenAPI (${relative(repoRoot, target)}, from ${vendored}) differs from ${version}. Run pnpm sync:opencode-openapi.`);
    process.exit(1);
  }
  console.log(`Vendored OpenCode OpenAPI matches ${version}.`);
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
  console.log(`Wrote ${relative(repoRoot, target)} from ${version}`);
}
